// Build the activity ID list for the system prompt (just IDs and labels)
export function getActivityCatalog() {
  return Object.entries(ACTIVITIES).map(([id, a]) => ({
    id,
    label: a.label,
    unit: a.unit,
    category: a.category,
    default_device: a.default_device,
  }));
}

// Lookup an activity by ID
export function getActivity(id) {
  return ACTIVITIES[id] || null;
}

// Get all activity IDs
export function getActivityIds() {
  return Object.keys(ACTIVITIES);
}

export default ACTIVITIES;
